#!/usr/bin/env python3
"""Generate Memory Gem pixel art and its eligible equipment catalog."""

import argparse
import struct
from pathlib import Path

from PIL import Image, ImageDraw

from add_custom_items import (
    B, FLAG_MOVEABLE, FLAG_PICKUPABLE, ITEM_ATTR_WEAPON2, ROOT, SPRITES, load_otb, node_ids,
)

DATA = ROOT / "server/YurOTS/ots/data"
CATALOG = DATA / "actions/lib/memory_gem_equipment.lua"
ITEM_ATTR_SLOT = 0x15
ARMOR_SLOT = b"\x02\x00"
FLAG_STACKABLE = 1 << 7
WEAPON_TYPES = {1, 2, 3, 5}
FIXED_WEAPONS = {20137, 2352, 20211, 20212, 20213, 20250, 20251, 20252, 20660}


def draw_gem(shard=False):
    art = Image.new("RGBA", (32, 32))
    draw = ImageDraw.Draw(art)
    if shard:
        draw.polygon(((10, 24), (13, 15), (20, 9), (25, 13), (24, 21), (17, 27)),
                     fill="#9275a3", outline="#272239")
        draw.polygon(((14, 16), (20, 10), (24, 13), (19, 19), (15, 23)), fill="#fbdfdf")
        draw.polygon(((19, 19), (24, 14), (23, 21), (17, 26), (17, 21)), fill="#789db7")
        draw.line(((14, 17), (20, 11), (22, 12)), fill="#fff9de")
        draw.point((20, 21), fill="#c4f0e8")
        return art
    draw.polygon(((5, 16), (9, 8), (17, 5), (24, 7), (29, 14), (27, 23),
                  (20, 28), (11, 26), (6, 22)), fill="#786b96", outline="#282137")
    draw.polygon(((6, 16), (10, 9), (17, 6), (24, 8), (27, 13), (18, 12), (13, 15)),
                 fill="#f5d6e1")
    draw.polygon(((13, 15), (19, 12), (25, 13), (27, 17), (23, 22), (17, 24), (11, 21)),
                 fill="#e7f6ec")
    draw.polygon(((6, 16), (13, 15), (11, 21), (17, 24), (18, 27), (12, 25), (7, 21)),
                 fill="#c493ae")
    draw.polygon(((27, 14), (28, 16), (26, 23), (20, 27), (18, 27), (17, 24),
                  (23, 22), (25, 19)), fill="#7db9cb")
    draw.line(((7, 16), (11, 10), (17, 7), (21, 8)), fill="#fff7dc")
    draw.line(((13, 16), (19, 13), (24, 14)), fill="#fffdee")
    draw.line(((19, 24), (23, 22), (26, 19)), fill="#b4efec")
    draw.line(((14, 12), (14, 16)), fill="#fffdf1")
    draw.line(((12, 14), (16, 14)), fill="#fffdf1")
    return art


def equipment_catalog(otb):
    _, root = load_otb(otb)
    armor, weapons = set(), set()
    for node in root.children:
        sid, _, _ = node_ids(node)
        if sid is None:
            continue
        flags, blocks = B.parse_item_props(node.props)
        item_flags = struct.unpack("<I", flags)[0]
        wearable = FLAG_PICKUPABLE | FLAG_MOVEABLE
        if item_flags & (wearable | FLAG_STACKABLE) != wearable:
            continue
        if B.get_block_payload(blocks, ITEM_ATTR_SLOT) == ARMOR_SLOT:
            armor.add(sid)
        weapon = B.get_block_payload(blocks, ITEM_ATTR_WEAPON2) or b""
        if len(weapon) == 5 and weapon[0] in WEAPON_TYPES and sid not in FIXED_WEAPONS:
            weapons.add(sid)

    rows = ["-- Generated by scripts/client-rme/build_memory_gem.py from the current OTB.", "return {"]
    for family, ids in (("armor", armor), ("ruby", weapons)):
        rows.append("\t" + family + " = {")
        values = [f"[{sid}] = true" for sid in sorted(ids)]
        for start in range(0, len(values), 7):
            rows.append("\t\t" + ", ".join(values[start:start + 7]) + ",")
        rows.append("\t},")
    rows.append("}")
    return "\n".join(rows) + "\n"


def draw_shard_patterns():
    art = Image.new("RGBA", (32, 32 * 8))
    main_shard = draw_gem(shard=True)
    chip = main_shard.resize((19, 19), Image.Resampling.NEAREST)
    pile = ((3, 6), (15, 9), (6, 13), (12, 3), (-1, 12), (4, 0), (14, 13))
    for pattern in range(8):
        frame = Image.new("RGBA", (32, 32))
        for pos in pile[:pattern]:
            frame.alpha_composite(chip, pos)
        frame.alpha_composite(main_shard)
        art.paste(frame, (0, 32 * pattern))
    return art


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog-only", action="store_true")
    parser.add_argument("--otb", type=Path, default=DATA / "items/items-zagan-test.otb")
    args = parser.parse_args()
    if not args.catalog_only:
        draw_gem().save(SPRITES / "memory_gem.png")
        draw_shard_patterns().save(SPRITES / "memory_shard.png")
    CATALOG.write_text(equipment_catalog(args.otb))


if __name__ == "__main__":
    main()
