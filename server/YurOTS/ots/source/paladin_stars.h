#ifndef YUROTS_PALADIN_STARS_H
#define YUROTS_PALADIN_STARS_H

#include "const76.h"

inline bool isPaladinStar(unsigned short id)
{
	return id == ITEM_GALE_STAR || id == ITEM_VENOM_STAR || id == ITEM_STORM_STAR;
}

enum PaladinStarBalance {
	PALADIN_STAR_HIT_CHANCE = 85,
	GALE_STAR_DELAY_MS = 900,
	VENOM_STAR_DELAY_MS = 1333,
	STORM_STAR_DELAY_MS = 1500,
	VENOM_STAR_CHANCE = 25,
	VENOM_STAR_MIN_DAMAGE = 8,
	VENOM_STAR_MAX_DAMAGE = 12,
	VENOM_STAR_TICKS = 4,
	VENOM_STAR_INTERVAL_MS = 2000,
	STORM_STAR_CHANCE = 20,
	STORM_STAR_MIN_DAMAGE = 18,
	STORM_STAR_MAX_DAMAGE = 30
};

#endif
