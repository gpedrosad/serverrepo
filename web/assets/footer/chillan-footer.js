/* Footer en pixel art: el centro de Chillán (Catedral, Cruz Monumental, Plaza de Armas).
   Traído del proyecto "laboratorio" (~/proyectos/footer-endless, tools/gen-chillan.py genera el arte).
   4 canvas apilados con parallax al hacer scroll, loop a 8 fps (viento, gente, perro, palomas; de
   noche ventanas, faroles, estrellas y la cruz encendida). Día o noche según la hora del visitante.
   Con prefers-reduced-motion se pinta un solo cuadro. Sin JS queda la imagen fija. */
/* ---------- Living footer scene: centro de Chillán ----------
   Art + map generated by tools/gen-chillan.py (415×137). The map PNG carries, per pixel,
   the depth layer (R: Andes/buildings → cathedral, Cruz Monumental, trees → plaza,
   monument, benches, lamps → pedestrian brick promenade), animation flags (G) and a light group id (B).
   Rendered at 8 fps: wind in the trees, walkers, people chatting, a dog, pigeons, and at
   night flickering windows, lamps, stars and the lit cross. Far layers get scroll parallax. */
var SceneArt = (function () {
  var W = 415, H = 137;
  var F = { SWAY: 1, WINDOW: 2, LAMP: 4, CROSS: 8, STAR: 16, HALO: 32 };

  function buildMasks(map) {
    var N = W * H;
    var layerOf = new Uint8Array(N), flags = new Uint8Array(N), group = new Uint8Array(N);
    for (var i = 0; i < N; i++) {
      var r = map[4 * i];
      layerOf[i] = r > 220 ? 255 : Math.round(r / 60);
      flags[i] = map[4 * i + 1];
      group[i] = map[4 * i + 2];
    }

    // Light lists (pixel index + group) and the swaying foliage zone.
    var lights = { window: [], lamp: [], halo: [], cross: [], star: [] };
    var sway = new Uint8Array(N), swayZone = [];
    for (var j = 0; j < N; j++) {
      var f = flags[j];
      if (f & F.SWAY) sway[j] = 1;
      if (f & F.WINDOW) lights.window.push(j);
      if (f & F.LAMP) lights.lamp.push(j);
      if (f & F.HALO) lights.halo.push(j);
      if (f & F.CROSS) lights.cross.push(j);
      if (f & F.STAR) lights.star.push(j);
    }
    for (var k = 0; k < N; k++) if (sway[k] || sway[k - 1] || sway[k + 1]) swayZone.push(k);

    // Per-layer source maps: each layer also paints "behind" nearer layers
    // (mirrored upward or nearest same-row pixel) so parallax never shows holes.
    var has = function (layer, x, y) { return x >= 0 && x < W && layerOf[y * W + x] === layer; };
    var nearest = function (layer, x, y) {
      var d = 1;
      while (d < W && !has(layer, x - d, y) && !has(layer, x + d, y)) d++;
      if (d === W) return -1;
      var dir = has(layer, x - d, y) ? -1 : 1, o = x + dir * d;
      for (var t = d - 1; t >= 0; t--) if (has(layer, o + dir * t, y)) return y * W + o + dir * t;
      return -1;
    };
    var sources = [0, 1, 2, 3].map(function (layer) {
      var src = new Int32Array(N).fill(-1);
      for (var x = 0; x < W; x++) {
        var last = -1;
        for (var y = 0; y < H; y++) {
          var o = y * W + x, l = layerOf[o];
          if (l === layer) { src[o] = o; last = y; }
          else if (l === 255) continue;
          else if (l < layer) last = -1;
          else if (last >= 0) {
            var mirror = (2 * last - y + 1) * W + x;
            var fm = ((layer === 0 || layer === 2) && mirror >= 0 && layerOf[mirror] === layer) ? mirror : nearest(layer, x, y);
            src[o] = fm >= 0 ? fm : (o - W >= 0 ? src[o - W] : -1);
          }
        }
      }
      return src;
    });

    var toArr = function (a) { return Int32Array.from(a); };
    return {
      sway: sway, swayZone: toArr(swayZone), sources: sources, group: group,
      window: toArr(lights.window), lamp: toArr(lights.lamp), halo: toArr(lights.halo),
      cross: toArr(lights.cross), star: toArr(lights.star)
    };
  }

  return { W: W, H: H, buildMasks: buildMasks };
})();

/* ---------- Sprites (drawn straight into a layer canvas, after the split) ---------- */
var Sprites = (function () {
  var W = SceneArt.W, H = SceneArt.H;
  function hex(s) { return [parseInt(s.slice(1, 3), 16), parseInt(s.slice(3, 5), 16), parseInt(s.slice(5, 7), 16)]; }
  function pack(c) { return ((255 << 24) | (c[2] << 16) | (c[1] << 8) | c[0]) >>> 0; }
  function dusk(c) { return [c[0] * .42 + 10 | 0, c[1] * .45 + 12 | 0, c[2] * .55 + 26 | 0]; }
  // Palette lookup for a theme: day colours as-is, night darkened unless "lit".
  function palette(obj, night) {
    var out = {};
    for (var k in obj) out[k] = pack(night ? dusk(hex(obj[k])) : hex(obj[k]));
    return out;
  }
  function put(out, x, y, col) { if (x >= 0 && x < W && y >= 0 && y < H) out[y * W + x] = col; }
  // rows: strings, '.' = transparent; (x, y) = top-left; mirror flips horizontally.
  function blit(out, rows, x, y, pal, mirror) {
    for (var r = 0; r < rows.length; r++) {
      var row = rows[r], n = row.length;
      for (var i = 0; i < n; i++) {
        var ch = mirror ? row[n - 1 - i] : row[i];
        if (ch !== "." && pal[ch] !== undefined) put(out, x + i, y + r, pal[ch]);
      }
    }
  }

  // Walker: 3 px wide, 8 tall (kids 7). Legs/arms alternate with position, so they only "walk" when moving.
  function person(out, x, feet, dir, pal, kid) {
    var step = (Math.floor(x / 2) & 1) === 0;
    var rows = [".h.", dir > 0 ? "hs." : ".sh", "ttt"];
    if (!kid) rows.push("ttt");
    rows.push(step ? "sts" : ".t.", "ppp", step ? "p.p" : ".p.", step ? "k.k" : ".k.");
    blit(out, rows, x - 1, feet - rows.length + 1, pal, false);
  }

  var PIGEON = {
    stand: ["..h", "wgg"],
    peck:  ["wg.", ".gh"],
    fly0:  ["w...w", ".wgh."],
    fly1:  [".....", "wwggh"]
  };
  function pigeon(out, x, y, dir, pose, pal) {
    var rows = PIGEON[pose];
    blit(out, rows, x - (rows[0].length >> 1), y - 1, pal, dir < 0);
  }

  // Dog on a leash, 6×4, trotting (legs alternate every frame).
  function dog(out, x, feet, dir, f8, pal) {
    var rows = ["....e.", "dddddn", "dddddd", (f8 & 1) ? "d.d.d." : ".d..d."];
    blit(out, rows, x - 3, feet - 3, pal, dir < 0);
    // leash from the walker's hand to the collar
    var hx0 = x - dir * 5, hx1 = x + dir * 2;
    for (var k = 1; k <= 6; k++) put(out, Math.round(hx0 + (hx1 - hx0) * k / 7), feet - 3 + (k >= 2 && k <= 5 ? 1 : 0), pal.l);
  }

  return { hex: hex, pack: pack, palette: palette, put: put, blit: blit,
           person: person, pigeon: pigeon, dog: dog };
})();

(function () {
  var W = SceneArt.W, H = SceneArt.H, S = Sprites;
  var scene = document.getElementById("scene");
  var ART = "/assets/footer/";
  // Noche de 20:00 a 7:00 (hora del visitante).
  function isNight() { var h = new Date().getHours(); return h >= 20 || h < 7; }
  function applyStill() { scene.classList.toggle("night", isNight()); }
  applyStill();
  var canvases = Array.prototype.slice.call(scene.querySelectorAll("canvas"));
  var ctxs = canvases.map(function (c) { return c.getContext("2d"); });
  var DEPTH = [10, 7, 3];                       // art-pixels of parallax per far layer
  var reduceMQ = matchMedia("(prefers-reduced-motion: reduce)");

  // People: layer 2 = paseo de la plaza (feet y 109), layer 3 = paseo peatonal de adoquín (feet y 123-136).
  // sp 0 = standing (groups chatting in front of the cathedral and on the promenade).
  var P = {
    a: { h: "#2b211c", s: "#e2b48e", t: "#c0453a", p: "#2f3b55", k: "#1d1d1f" },
    b: { h: "#d9c38f", s: "#efc9a6", t: "#3f7fbf", p: "#e9e4d8", k: "#5a4030" },
    c: { h: "#4a2f20", s: "#c99670", t: "#f0c23a", p: "#3a3a40", k: "#202020" },
    d: { h: "#9a9a9a", s: "#e0b896", t: "#5c4b7a", p: "#2a2a2e", k: "#141414" },
    e: { h: "#1f1a18", s: "#b98563", t: "#2f8a6a", p: "#4a4038", k: "#1b1b1b" },
    f: { h: "#6b3b22", s: "#efc4a0", t: "#e7e2d6", p: "#3c5a8a", k: "#2b2b2b" },
    g: { h: "#2a2420", s: "#d6a582", t: "#b84d7a", p: "#2b2b33", k: "#1a1a1a" },
    i: { h: "#3b2a1e", s: "#d9a77f", t: "#e07b39", p: "#33415c", k: "#1c1c1c" },
    j: { h: "#141414", s: "#a87454", t: "#f2efe6", p: "#1f2a44", k: "#101010" },
    l: { h: "#b5651d", s: "#f0caa8", t: "#6aa0c8", p: "#5b4636", k: "#2a2a2a" },
    m: { h: "#555049", s: "#dcb08a", t: "#8a3b3b", p: "#3d3d3d", k: "#181818" }
  };
  var WALKERS = [
    { L: 3, y: 124, sp: 7,   dir:  1, x0: 30,  pal: P.a },
    { L: 3, y: 127, sp: 6,   dir: -1, x0: 210, pal: P.b, night: true },
    { L: 3, y: 125, sp: 6,   dir:  1, x0: 310, pal: P.c, kid: true },
    { L: 3, y: 130, sp: 5.5, dir: -1, x0: 40,  pal: P.d, night: true },
    { L: 3, y: 133, sp: 8,   dir:  1, x0: 150, pal: P.i },
    { L: 3, y: 135, sp: 6.5, dir: -1, x0: 330, pal: P.j, night: true },
    { L: 3, y: 132, sp: 5,   dir:  1, x0: 255, pal: P.l, dog: true },
    { L: 3, y: 129, sp: 4.5, dir: -1, x0: 120, pal: P.g },      // couple
    { L: 3, y: 129, sp: 4.5, dir: -1, x0: 124, pal: P.f, night: true },
    { L: 3, y: 136, sp: 7.5, dir:  1, x0: 380, pal: P.m },
    { L: 3, y: 134, sp: 0,   dir:  1, x0: 196, pal: P.e, night: true },   // chatting
    { L: 3, y: 134, sp: 0,   dir: -1, x0: 200, pal: P.c },
    { L: 3, y: 135, sp: 0,   dir: -1, x0: 204, pal: P.b, kid: true },
    { L: 3, y: 126, sp: 0,   dir:  1, x0: 72,  pal: P.m },
    { L: 3, y: 126, sp: 0,   dir: -1, x0: 76,  pal: P.l, night: true },
    { L: 2, y: 109, sp: 4,   dir: -1, x0: 140, pal: P.e },
    { L: 2, y: 110, sp: 4.5, dir:  1, x0: 250, pal: P.f, night: true },
    { L: 2, y: 109, sp: 3.5, dir:  1, x0: 400, pal: P.g },
    { L: 2, y: 110, sp: 3,   dir: -1, x0: 300, pal: P.i, kid: true },
    { L: 2, y: 103, sp: 0,   dir:  1, x0: 236, pal: P.j },              // at the cathedral door
    { L: 2, y: 103, sp: 0,   dir: -1, x0: 244, pal: P.a, night: true }
  ];
  // Pigeons around the monument and on the sidewalk: [layer, x, y, dir, phase]
  var PIGEONS = [[2, 100, 108, 1, 0], [2, 104, 109, -1, 1.3], [2, 58, 108, 1, .7], [2, 214, 109, -1, 2.1],
                 [3, 288, 124, 1, .4], [3, 294, 125, -1, 1.9], [3, 100, 131, 1, 2.6], [3, 236, 133, -1, 1.1]];
  var PIGEON_PAL = { g: "#8e939f", w: "#a9aeb8", h: "#5d6273" };

  var state = null;        // { day, night, masks }
  var inView = false, loading = false, timer = 0, rafPending = false;

  function loadPixels(src) {
    return new Promise(function (resolve, reject) {
      var img = new Image();
      img.onload = function () {
        try {
          var c = document.createElement("canvas");
          c.width = W; c.height = H;
          var ctx = c.getContext("2d", { willReadFrequently: true });
          ctx.drawImage(img, 0, 0);
          resolve(ctx.getImageData(0, 0, W, H).data);   // throws on file:// (tainted)
        } catch (e) { reject(e); }
      };
      img.onerror = reject;
      img.src = src;
    });
  }

  function now8() { return Math.floor(performance.now() / 1000 * 8) / 8; }  // quantised 8 fps clock
  function hash(a, b) { var v = Math.sin(a * 127.1 + b * 311.7) * 43758.5453; return v - Math.floor(v); }
  function wrap(v, m) { return ((v % m) + m) % m; }

  function makeRenderer() {
    var dark = isNight();
    var base = dark ? state.night : state.day;
    var base32 = new Uint32Array(base.buffer);
    var frame = new Uint8ClampedArray(W * H * 4);
    var frame32 = new Uint32Array(frame.buffer);
    var masks = state.masks, group = masks.group;
    var gust = new Float32Array(W);
    var layers = ctxs.map(function (ctx, i) {
      var img = new ImageData(W, H);
      return { ctx: ctx, img: img, out: new Uint32Array(img.data.buffer), src: masks.sources[i] };
    });
    function tint(o, col, a) {                     // blend pixel o of the frame toward col
      var d = o * 4;
      frame[d]     = frame[d]     + (col[0] - frame[d])     * a;
      frame[d + 1] = frame[d + 1] + (col[1] - frame[d + 1]) * a;
      frame[d + 2] = frame[d + 2] + (col[2] - frame[d + 2]) * a;
    }
    var WARM = [255, 214, 130], OFF = [24, 30, 46], TV = [120, 160, 255], WHITE = [255, 250, 232], NIGHTSKY = [10, 10, 10];

    // Sprite palettes for this theme.
    var walkers = WALKERS.filter(function (w) { return !dark || w.night; }).map(function (w) {
      return { w: w, pal: S.palette(w.pal, dark) };
    });
    var pigeonPal = S.palette(PIGEON_PAL, dark);
    var dogPal = S.palette({ d: "#8a5a34", e: "#5a3a22", n: "#1d1d1f", l: "#c0453a" }, dark);

    return function render(t) {
      frame32.set(base32);
      var f8 = Math.round(t * 8);                 // integer frame counter

      // Wind: a travelling gust shifts leaf pixels ±1px (plaza trees, flower beds).
      for (var x = 0; x < W; x++) gust[x] = Math.sin(0.45 * t - 0.012 * x);
      var zone = masks.swayZone, sway = masks.sway;
      for (var z = 0; z < zone.length; z++) {
        var o = zone[z], ox = o % W, g = gust[ox];
        if (g <= 0.55) continue;
        var oy = (o - ox) / W;
        var u = g * (0.85 * Math.sin(2.2 * t - 0.05 * ox + 0.1 * oy) + 0.15);
        var a = u > 0.6 ? 1 : u < -0.6 ? -1 : 0;
        if (!a) continue;
        var c = sway[o - a] ? o - a : sway[o] ? o + a : -1;
        if (c >= 0) frame32[o] = base32[c] || 0;
      }

      if (dark) {
        // Windows: now and then someone switches a light on/off; a few rooms have the TV on.
        var win = masks.window;
        for (var wi = 0; wi < win.length; wi++) {
          var wo = win[wi], gr = group[wo];
          var period = 5 + (gr * 7) % 9, k = Math.floor((t + gr * 1.37) / period);
          var lit = frame[wo * 4] > 150;
          if (hash(gr, k) < 0.12) tint(wo, lit ? OFF : WARM, lit ? 0.85 : 0.8);
          else if (lit && gr % 13 === 5) tint(wo, TV, 0.2 + 0.3 * hash(gr, f8));
        }
        // Lamps: gentle shimmer, one tired lamp that flickers.
        var lamp = masks.lamp;
        for (var li = 0; li < lamp.length; li++) {
          var lo = lamp[li], lg = group[lo];
          if (lg === 4 && hash(lg, f8) < 0.18) tint(lo, OFF, 0.55);
          else tint(lo, WHITE, 0.25 * hash(lg + li, f8));
        }
        var halo = masks.halo, hb = 0.08 * Math.sin(3.1 * t);
        if (hb > 0) for (var hi = 0; hi < halo.length; hi++) tint(halo[hi], WARM, hb);
        // The cross in the Cruz Monumental breathes softly.
        var cross = masks.cross, ca = 0.3 * (0.5 + 0.5 * Math.sin(1.1 * t));
        for (var ci = 0; ci < cross.length; ci++) tint(cross[ci], WHITE, ca);
        // Stars twinkle.
        var star = masks.star;
        for (var si = 0; si < star.length; si++) {
          var sg = group[star[si]], v = Math.sin(t * (1.3 + (sg % 5) * 0.45) + sg * 2.1);
          if (v < -0.55) tint(star[si], NIGHTSKY, 0.65);
          else if (v > 0.9) tint(star[si], WHITE, 0.6);
        }
      }

      // Split into the 4 depth canvases.
      for (var L = 0; L < layers.length; L++) {
        var ly = layers[L], src = ly.src, out = ly.out;
        for (var i = 0; i < out.length; i++) { var sj = src[i]; out[i] = sj >= 0 ? frame32[sj] : 0; }
      }

      // Walkers (wrap around the scene), then pigeons that flutter up when someone passes.
      var pos = [];
      for (var p = 0; p < walkers.length; p++) {
        var wk = walkers[p].w;
        var px = Math.round(wrap(wk.x0 + wk.dir * wk.sp * t, W + 24) - 12);
        pos.push([wk.L, px, wk.y]);
        S.person(layers[wk.L].out, px, wk.y, wk.dir, walkers[p].pal, wk.kid);
        if (wk.dog) S.dog(layers[wk.L].out, px + wk.dir * 6, wk.y, wk.dir, f8, dogPal);
      }
      if (!dark) {
        for (var q = 0; q < PIGEONS.length; q++) {
          var pg = PIGEONS[q], gx = pg[1] + Math.round(1.5 * Math.sin(0.35 * t + pg[4] * 3)), gy = pg[2];
          var scared = pos.some(function (w) { return w[0] === pg[0] && Math.abs(w[1] - gx) < 6 && Math.abs(w[2] - gy) < 4; });
          var pose = scared ? (f8 & 1 ? "fly0" : "fly1") : (((t + pg[4]) % 2.2) < 0.5 ? "peck" : "stand");
          S.pigeon(layers[pg[0]].out, gx, scared ? gy - 3 : gy, pg[3], pose, pigeonPal);
        }
        // A small flock crosses the sky every 28 s.
        var tf = wrap(t, 28);
        for (var b = 0; b < 4; b++) {
          var bx = Math.round(-12 + tf * 38 - b * 8), by = Math.round(26 + b * 3 + 2 * Math.sin(tf * 3 + b));
          if (bx > -6 && bx < W + 6) S.pigeon(layers[3].out, bx, by, 1, (f8 + b) & 1 ? "fly0" : "fly1", pigeonPal);
        }
      }

      for (var Lp = 0; Lp < layers.length; Lp++) layers[Lp].ctx.putImageData(layers[Lp].img, 0, 0);
    };
  }

  function stop() { if (timer) { clearInterval(timer); timer = 0; } }
  function start() {
    stop();
    if (!state) return;
    var render = makeRenderer();
    render(now8());                                   // always paint one frame
    if (inView && !reduceMQ.matches) timer = setInterval(function () { render(now8()); }, 125);
  }

  // Scroll parallax: offset ["start end", "end end"] on the far canvases.
  function parallax() {
    rafPending = false;
    if (reduceMQ.matches) { for (var i = 0; i < 3; i++) canvases[i].style.transform = ""; return; }
    var rect = scene.getBoundingClientRect(), vh = window.innerHeight;
    var progress = rect.height ? Math.min(1, Math.max(0, (vh - rect.top) / rect.height)) : 1;
    var scale = scene.offsetHeight / H, dpr = window.devicePixelRatio || 1;
    for (var j = 0; j < 3; j++) {
      var y = Math.round(-(1 - progress) * DEPTH[j] * scale * dpr) / dpr;
      canvases[j].style.transform = "translate3d(0," + y + "px,0)";
    }
  }
  function queueParallax() { if (!rafPending) { rafPending = true; requestAnimationFrame(parallax); } }

  function ensureLoaded() {
    if (state || loading) return;
    loading = true;
    Promise.all([loadPixels(ART + "chillan-day.png"), loadPixels(ART + "chillan-night.png"), loadPixels(ART + "chillan-map.png")])
      .then(function (res) {
        state = { day: res[0], night: res[1], masks: SceneArt.buildMasks(res[2]) };
        scene.classList.add("is-live");
        parallax();
        start();
      })
      .catch(function () { /* e.g. file:// tainted canvas: keep the still image */ });
  }

  if (!ctxs[0] || !("IntersectionObserver" in window)) return;   // still image only

  new IntersectionObserver(function (entries) {
    inView = entries[0].isIntersecting;
    if (inView) { ensureLoaded(); if (state) start(); } else stop();
  }, { rootMargin: "200px" }).observe(scene);

  window.addEventListener("scroll", queueParallax, { passive: true });
  window.addEventListener("resize", queueParallax);
  reduceMQ.addEventListener("change", function () { parallax(); if (state) start(); });
  // Al pasar de día a noche (o al revés) con la página abierta, se cambia la escena.
  var lastNight = isNight();
  setInterval(function () {
    if (isNight() !== lastNight) { lastNight = isNight(); applyStill(); if (state) start(); }
  }, 60000);
  document.addEventListener("visibilitychange", function () {
    if (document.hidden) stop(); else if (state && inView) start();
  });
})();
